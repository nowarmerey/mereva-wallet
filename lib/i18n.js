const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [locale, setLocaleState] = useState("en");

  useEffect(() => {
    const saved = localStorage.getItem("locale") || "en";
    applyLocale(saved);
    setLocaleState(saved);
  }, []);

  function applyLocale(code) {
    const meta = LOCALES.find((l) => l.code === code) || LOCALES[0];
    document.documentElement.lang = code;
    document.documentElement.dir = meta.dir;
  }

  function setLocale(code) {
    localStorage.setItem("locale", code);
    applyLocale(code);
    setLocaleState(code);
  }

  // t(key, vars?) — supports {n}/{name} interpolation.
  function t(key, vars) {
    let s = DICT[locale]?.[key] ?? DICT.en[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, vars[k]);
    return s;
  }

  const dir = (LOCALES.find((l) => l.code === locale) || LOCALES[0]).dir;

  return (
    <I18nContext.Provider value={{ locale, setLocale, t, dir }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx)
    return { locale: "en", setLocale: () => {}, t: (k) => DICT.en[k] ?? k, dir: "ltr" };
  return ctx;
}
